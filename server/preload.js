'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  refocus: () => ipcRenderer.send('refocus'),
  getStatus: () => ipcRenderer.invoke('get-status'),
  getUsers: () => ipcRenderer.invoke('get-users'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  getDataDir: () => ipcRenderer.invoke('get-data-dir'),
  addUser: (u) => ipcRenderer.invoke('add-user', u),
  updateUser: (id, patch) => ipcRenderer.invoke('update-user', id, patch),
  deleteUser: (id) => ipcRenderer.invoke('delete-user', id),
  resetPw: (id, pw) => ipcRenderer.invoke('reset-pw', id, pw),
  bulkAdd: (text) => ipcRenderer.invoke('bulk-add', text),
  setPort: (port) => ipcRenderer.invoke('set-port', port),
  getAutostart: () => ipcRenderer.invoke('get-autostart'),
  setAutostart: (on) => ipcRenderer.invoke('set-autostart', on),
  setSchoolName: (name) => ipcRenderer.invoke('set-school-name', name),
  registerClientUpdate: () => ipcRenderer.invoke('register-client-update'),
  getDeptOrder: () => ipcRenderer.invoke('get-dept-order'),
  setDeptOrder: (order) => ipcRenderer.invoke('set-dept-order', order),
  getSignups: () => ipcRenderer.invoke('get-signups'),
  approveSignup: (reqId) => ipcRenderer.invoke('approve-signup', reqId),
  rejectSignup: (reqId) => ipcRenderer.invoke('reject-signup', reqId),
  getLogs: () => ipcRenderer.invoke('get-logs'),
  backupExport: () => ipcRenderer.invoke('backup-export'),
  backupImport: () => ipcRenderer.invoke('backup-import'),
  changeDataDir: () => ipcRenderer.invoke('change-data-dir'),
  openLog: () => ipcRenderer.send('open-log'),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  getClientUpdate: () => ipcRenderer.invoke('get-client-update'),
  exportCsv: () => ipcRenderer.invoke('export-csv'),
  importCsv: () => ipcRenderer.invoke('import-csv'),
  getStorage: () => ipcRenderer.invoke('get-storage'),
  setRetention: (days) => ipcRenderer.invoke('set-retention', days),
  runCleanup: () => ipcRenderer.invoke('run-cleanup'),
  onStatus: (cb) => ipcRenderer.on('status', (e, s) => cb(s)),
  onUsers: (cb) => ipcRenderer.on('users', (e, u) => cb(u))
});
